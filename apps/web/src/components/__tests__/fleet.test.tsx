import { act, fireEvent, render, screen, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { beforeEach, describe, expect, it, vi } from "vitest";
import { FleetFilters } from "@/components/fleet/fleet-filters";
import { ProvenanceBanner } from "@/components/fleet/provenance-banner";
import { CarrierAssociationText } from "@/components/fleet/vessel-panel";
import { DEFAULT_FILTERS } from "@/lib/fleet";
import type { FleetPositions, VesselDetail } from "@/lib/types";
import { mockFetch, renderWithQuery } from "@/test/utils";

// MapLibre needs WebGL, which jsdom lacks: replace the map with a probe that exposes props.
const mapProps = vi.hoisted(() => ({ current: null as null | Record<string, unknown> }));
vi.mock("@/components/fleet/fleet-map", () => ({
  FleetMap: (props: Record<string, unknown>) => {
    mapProps.current = props;
    const vessels = props.vessels as { id: string }[];
    return <div data-testid="fleet-map" data-count={vessels.length} />;
  },
}));
vi.mock("next-themes", () => ({ useTheme: () => ({ resolvedTheme: "light" }) }));

class FakeSocket {
  static instances: FakeSocket[] = [];
  onopen: (() => void) | null = null;
  onmessage: ((e: { data: string }) => void) | null = null;
  onclose: (() => void) | null = null;
  constructor(public url: string) {
    FakeSocket.instances.push(this);
  }
  close() {}
}

const NOW_ISO = new Date().toISOString();
const positions = (): FleetPositions => ({
  type: "FeatureCollection",
  features: [
    { type: "Feature", id: "v1", geometry: { type: "Point", coordinates: [4.5, 51.9] },
      properties: { id: "v1", mmsi: 200000001, name: "SYNTHETIC AEX 01", vessel_class: "cargo", carrier: null,
        sog_knots: 17, cog_deg: 80, heading_deg: 80, nav_status: 0, observed_at: NOW_ISO, age_seconds: 5,
        freshness: "live", source: "ais-simulator", data_mode: "synthetic" } },
    { type: "Feature", id: "v2", geometry: { type: "Point", coordinates: [103.8, 1.3] },
      properties: { id: "v2", mmsi: 200000017, name: "SYNTHETIC MEG 17", vessel_class: "tanker", carrier: "msc",
        sog_knots: 13, cog_deg: 270, heading_deg: 270, nav_status: 0, observed_at: NOW_ISO, age_seconds: 5,
        freshness: "live", source: "ais-simulator", data_mode: "synthetic" } },
  ],
  meta: { generated_at: NOW_ISO, count: 2, truncated: false, by_data_mode: { synthetic: 2 }, seen_within_s: 86400 },
}); // prettier-ignore

describe("ProvenanceBanner", () => {
  it("calls out synthetic data and polling fallback", () => {
    render(<ProvenanceBanner counts={{ synthetic: 3 }} live="offline" updatedAt={null} />);
    expect(screen.getByTestId("synthetic-banner")).toHaveTextContent("3 vessels are generated by the ChainSight AIS simulator");
    expect(screen.getByTestId("live-status")).toHaveTextContent("Live stream unavailable");
  });
  it("shows no synthetic warning for real-time data", () => {
    render(<ProvenanceBanner counts={{ real_time: 10 }} live="live" updatedAt={null} />);
    expect(screen.queryByTestId("synthetic-banner")).not.toBeInTheDocument();
    expect(screen.getByTestId("live-status")).toHaveTextContent("Streaming");
  });
});

describe("FleetFilters", () => {
  it("toggles class groups and sets carrier and recency", async () => {
    const onChange = vi.fn();
    render(<FleetFilters value={DEFAULT_FILTERS} onChange={onChange} carriers={[{ code: "msc", name: "MSC" }]} mode="light" />);
    await userEvent.click(screen.getByRole("button", { name: /Tanker/ }));
    expect(onChange).toHaveBeenLastCalledWith({ ...DEFAULT_FILTERS, groups: ["tanker"] });
    fireEvent.change(screen.getByLabelText("Carrier"), { target: { value: "msc" } });
    expect(onChange).toHaveBeenLastCalledWith({ ...DEFAULT_FILTERS, carrier: "msc" });
    fireEvent.change(screen.getByLabelText("Seen"), { target: { value: "live" } });
    expect(onChange).toHaveBeenLastCalledWith({ ...DEFAULT_FILTERS, freshness: "live" });
  });
});

describe("CarrierAssociationText", () => {
  it("explains how an association was inferred", () => {
    render(
      <CarrierAssociationText
        carrier={{ carrier_code: "msc", carrier_name: "MSC", relation: "operator", method: "name_heuristic", confidence: 0.6, valid_from: NOW_ISO }}
      />,
    );
    expect(screen.getByText(/Inferred from vessel name · 60% confidence/)).toBeInTheDocument();
  });
  it("never invents an operator", () => {
    render(<CarrierAssociationText carrier={null} />);
    expect(screen.getByText("No known operator")).toBeInTheDocument();
  });
});

describe("FleetView", () => {
  beforeEach(() => {
    FakeSocket.instances = [];
    vi.stubGlobal("WebSocket", FakeSocket);
  });

  async function renderView() {
    const { FleetView } = await import("@/components/fleet/fleet-view");
    mockFetch((path) => {
      if (path === "/api/v1/fleet/positions") return { body: positions() };
      if (path === "/api/v1/carriers") return { body: { items: [], total: 0, limit: 200, offset: 0 } };
      return "pending";
    });
    renderWithQuery(<FleetView />);
    await screen.findByText("SYNTHETIC AEX 01");
  }

  it("loads positions, labels them synthetic and lists them as a table view", async () => {
    await renderView();
    expect(screen.getByTestId("fleet-map")).toHaveAttribute("data-count", "2");
    expect(screen.getByTestId("synthetic-banner")).toBeInTheDocument();
    const list = screen.getByRole("region", { name: "Vessels in view" });
    expect(within(list).getAllByRole("button")).toHaveLength(2);
  });

  it("filters map state by class", async () => {
    await renderView();
    await userEvent.click(screen.getByRole("button", { name: /^Tanker$/ }));
    expect(screen.getByTestId("fleet-map")).toHaveAttribute("data-count", "1");
    expect(screen.queryByText("SYNTHETIC AEX 01")).not.toBeInTheDocument();
  });

  it("applies live WebSocket updates and reports streaming status", async () => {
    await renderView();
    const ws = FakeSocket.instances[0]!;
    act(() => ws.onopen?.());
    expect(screen.getByTestId("live-status")).toHaveTextContent("Streaming");
    act(() =>
      ws.onmessage?.({
        data: JSON.stringify({
          type: "positions", source: "ais-simulator", data_mode: "synthetic",
          positions: [{ vessel_id: "v3", mmsi: 200000020, name: "SYNTHETIC LNG 24", vessel_class: "tanker",
            lat: 25, lon: 57, sog_knots: 18, cog_deg: 120, heading_deg: 120, nav_status: 0,
            observed_at: new Date().toISOString() }],
        }),
      }),
    ); // prettier-ignore
    expect(screen.getByTestId("fleet-map")).toHaveAttribute("data-count", "3");
    expect(await screen.findByText("SYNTHETIC LNG 24")).toBeInTheDocument();
  });

  it("selecting a vessel from the list selects it on the map", async () => {
    await renderView();
    await userEvent.click(screen.getByText("SYNTHETIC MEG 17"));
    expect(mapProps.current?.selectedId).toBe("v2");
    expect(screen.getByRole("complementary", { name: "Vessel details" })).toBeInTheDocument();
  });
});

describe("VesselView", () => {
  const vessel: VesselDetail = {
    id: "v1", mmsi: 200000001, imo: null, name: "SYNTHETIC AEX 01", vessel_class: "cargo",
    vessel_class_source: "ais_ship_type", destination: "NL RTM", carrier: null, call_sign: "SYN001",
    ship_type_code: 70, length_m: 366, beam_m: 51, draught_m: 14, first_seen_at: NOW_ISO,
    identifiers: [{ scheme: "mmsi", value: "200000001", valid_from: NOW_ISO, valid_to: null, source: "ais-simulator" }],
    carrier_history: [], open_port_call: null,
    position: { lat: 51.9, lon: 4.5, sog_knots: 0, cog_deg: null, heading_deg: null, nav_status: 5,
      nav_status_label: "Moored", observed_at: NOW_ISO, age_seconds: 5, freshness: "live",
      provenance: { source: "ais-simulator", data_mode: "synthetic" } },
  }; // prettier-ignore

  it("warns that a synthetic vessel is not real and shows unknown arrivals honestly", async () => {
    const { VesselView } = await import("@/components/vessel/vessel-view");
    mockFetch((path) => {
      if (path === "/api/v1/vessels/v1") return { body: vessel };
      if (path.endsWith("/port-calls")) {
        return { body: { items: [{ id: "c1", vessel_id: "v1", vessel_name: null, actual_arrival_at: null,
          actual_departure_at: null, duration_seconds: null, detection_method: "ais_geofence", source: "ais-simulator",
          port: { id: "p1", unlocode: "NLRTM", name: "Rotterdam", country_code: "NL" } }], total: 1, limit: 50, offset: 0 } };
      } // prettier-ignore
      if (path.endsWith("/track")) return "pending";
      return "pending";
    });
    renderWithQuery(<VesselView id="v1" />);
    expect(await screen.findByText(/It is not a real ship/)).toBeInTheDocument();
    expect(await screen.findByText("Before tracking began")).toBeInTheDocument();
    expect(screen.getByText(/from AIS ship type/)).toBeInTheDocument();
  });

  it("shows a not-found state for unknown vessels", async () => {
    const { VesselView } = await import("@/components/vessel/vessel-view");
    mockFetch(() => ({ status: 404, body: { error: { code: "vessel_not_found", message: "Vessel not found", details: null, request_id: "r" } } }));
    renderWithQuery(<VesselView id="nope" />);
    expect(await screen.findByText("Vessel not found")).toBeInTheDocument();
  });
});
