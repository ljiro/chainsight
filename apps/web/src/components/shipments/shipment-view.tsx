"use client";

import { ArrowLeft, ExternalLink, Loader2, RefreshCw, Ship } from "lucide-react";
import Link from "next/link";
import type { ReactNode } from "react";
import { DelayBadge, ShipmentStatusBadge, formatDelay } from "@/components/shipments/badges";
import { EmptyState, ErrorState, LoadingRows } from "@/components/query-state";
import { StatusBadge } from "@/components/status-badge";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { ApiError } from "@/lib/api";
import { buildMilestoneRows, estimateHistory } from "@/lib/milestones";
import { useRefreshShipment, useShipment } from "@/lib/queries";
import type { ShipmentDetail } from "@/lib/types";
import { formatAge, formatCoord, formatTime } from "@/lib/utils";

function Kpi({ label, children, hint }: { label: string; children: ReactNode; hint?: string }) {
  return (
    <div>
      <p className="text-xs text-muted-foreground">{label}</p>
      <div className="mt-0.5 text-sm font-medium">{children}</div>
      {hint ? <p className="text-[11px] text-muted-foreground">{hint}</p> : null}
    </div>
  );
}

function etaSource(s: ShipmentDetail): string {
  if (s.actual_arrival_at) return "actual arrival";
  if (estimateHistory(s.events, s.destination.unlocode).length) return "latest carrier estimate";
  return s.current_eta_at ? "carrier plan" : "no schedule";
}

export function ShipmentView({ id }: { id: string }) {
  const shipment = useShipment(id);
  const refresh = useRefreshShipment(id);

  if (shipment.isPending) return <LoadingRows rows={6} />;
  if (shipment.error) {
    if (shipment.error instanceof ApiError && shipment.error.status === 404) {
      return (
        <EmptyState title="Shipment not found">
          <Link href="/shipments" className="text-primary hover:underline">Back to shipments</Link>
        </EmptyState>
      );
    }
    return <ErrorState error={shipment.error} onRetry={() => void shipment.refetch()} />;
  }
  const s = shipment.data;
  const rows = buildMilestoneRows(s.events);
  const estimates = estimateHistory(s.events, s.destination.unlocode);

  return (
    <div className="flex flex-col gap-6">
      <div className="flex flex-wrap items-end justify-between gap-4">
        <div>
          <Link href="/shipments" className="mb-2 inline-flex items-center gap-1 text-xs text-muted-foreground hover:text-foreground">
            <ArrowLeft className="size-3.5" aria-hidden /> Shipments
          </Link>
          <h1 className="text-xl font-semibold tracking-tight">{s.reference_value}</h1>
          <p className="text-xs text-muted-foreground">
            {s.carrier.name} · {s.reference_type.replace(/_/g, " ")}
            {s.containers.length ? ` · ${s.containers.join(", ")}` : ""}
          </p>
        </div>
        <div className="flex flex-wrap items-center gap-2">
          <ShipmentStatusBadge status={s.status} />
          <DelayBadge status={s.delay_status} hours={s.delay_hours} />
          <StatusBadge kind="mode" value={s.provenance.data_mode} />
          {s.refreshable ? (
            <Button variant="outline" size="sm" onClick={() => refresh.mutate()} disabled={refresh.isPending}>
              {refresh.isPending ? <Loader2 className="size-3.5 animate-spin" /> : <RefreshCw className="size-3.5" />}
              Refresh from carrier
            </Button>
          ) : null}
        </div>
      </div>

      {s.provenance.data_mode === "synthetic" ? (
        <p role="note" className="rounded-md border border-synthetic/30 bg-synthetic/10 px-3 py-2 text-sm">
          <span className="font-medium text-synthetic">Synthetic shipment</span>, generated by the demo carrier. Not a
          real booking.
        </p>
      ) : null}
      {refresh.error ? <ErrorState error={refresh.error} /> : null}

      <Card>
        <CardContent className="grid grid-cols-2 gap-4 pt-5 md:grid-cols-5">
          <Kpi label="Route">
            <span className="font-mono">{s.origin.unlocode ?? "—"}</span> →{" "}
            <span className="font-mono">{s.destination.unlocode ?? "—"}</span>
          </Kpi>
          <Kpi label="Original planned arrival" hint="Fixed at first plan; never overwritten">
            {formatTime(s.planned_arrival_at)}
          </Kpi>
          <Kpi label={s.actual_arrival_at ? "Actual arrival" : "Current ETA"} hint={`From ${etaSource(s)}`}>
            {formatTime(s.actual_arrival_at ?? s.current_eta_at)}
          </Kpi>
          <Kpi label="Delay vs original plan">
            {s.delay_hours != null ? formatDelay(s.delay_hours) : "—"}
          </Kpi>
          <Kpi label="Last carrier data" hint={s.last_refreshed_at ? `Refreshed ${formatAge(s.last_refreshed_at)}` : undefined}>
            {s.last_event_at ? formatAge(s.last_event_at) : "—"}
          </Kpi>
        </CardContent>
      </Card>

      <div className="grid gap-6 lg:grid-cols-3">
        <Card className="lg:col-span-2">
          <CardHeader>
            <CardTitle>Milestones</CardTitle>
            <CardDescription>Planned, estimated and actual events side by side (DCSA event codes, UTC).</CardDescription>
          </CardHeader>
          <CardContent>
            {rows.length === 0 ? (
              <EmptyState title="No events reported yet" />
            ) : (
              <div className="overflow-x-auto">
                <table className="w-full text-sm" aria-label="Milestones">
                  <thead>
                    <tr className="text-left text-[11px] tracking-wide text-muted-foreground uppercase">
                      <th className="py-2 pr-3 font-medium">Milestone</th>
                      <th className="py-2 pr-3 font-medium">Planned</th>
                      <th className="py-2 pr-3 font-medium">Estimated</th>
                      <th className="py-2 pr-3 font-medium">Actual</th>
                      <th className="py-2 font-medium">Variance</th>
                    </tr>
                  </thead>
                  <tbody className="divide-y">
                    {rows.map((r) => (
                      <tr key={r.key}>
                        <td className="py-2 pr-3">
                          <span className="font-medium">{r.description}</span>
                          <p className="text-xs text-muted-foreground">
                            <span className="font-mono">{r.location ?? "—"}</span>
                            {r.vessel ? ` · ${r.vessel}` : ""}
                            {r.code === "UNKNOWN" ? " · unmapped carrier code" : ""}
                          </p>
                        </td>
                        <td className="py-2 pr-3 whitespace-nowrap">
                          {formatTime(r.planned)}
                          {r.replanned ? <p className="text-[11px] text-muted-foreground">re-planned: {formatTime(r.replanned)}</p> : null}
                        </td>
                        <td className="py-2 pr-3 whitespace-nowrap">{r.estimate ? formatTime(r.estimate) : "—"}</td>
                        <td className="py-2 pr-3 whitespace-nowrap">
                          {r.actual ? formatTime(r.actual) : <span className="text-muted-foreground">pending</span>}
                        </td>
                        <td className="py-2 whitespace-nowrap tabular-nums">
                          {r.varianceHours != null ? formatDelay(r.varianceHours) : "—"}
                        </td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            )}
          </CardContent>
        </Card>

        <div className="flex flex-col gap-6">
          <Card>
            <CardHeader>
              <CardTitle>Vessels</CardTitle>
              <CardDescription>As reported by the carrier. The container moves with the vessel; AIS does not track the container itself.</CardDescription>
            </CardHeader>
            <CardContent>
              {s.legs.length === 0 ? (
                <EmptyState title="No vessel reported" />
              ) : (
                <ul className="flex flex-col gap-3">
                  {s.legs.map((leg) => (
                    <li key={leg.sequence} className="rounded-md border p-3 text-sm">
                      <div className="flex items-center justify-between gap-2">
                        <span className="flex items-center gap-1.5 font-medium">
                          <Ship className="size-3.5 text-muted-foreground" aria-hidden />
                          {leg.carrier_vessel_name ?? "Unnamed vessel"}
                        </span>
                        <span className="font-mono text-xs text-muted-foreground">{leg.carrier_voyage_number}</span>
                      </div>
                      <p className="text-xs text-muted-foreground">
                        Leg {leg.sequence}: <span className="font-mono">{leg.load_unlocode ?? "—"}</span> →{" "}
                        <span className="font-mono">{leg.discharge_unlocode ?? "—"}</span>
                        {leg.carrier_vessel_imo ? ` · IMO ${leg.carrier_vessel_imo}` : ""}
                      </p>
                      {leg.vessel_id && leg.vessel_position ? (
                        <div className="mt-2 flex flex-wrap items-center gap-2 text-xs">
                          <StatusBadge kind="position" value={leg.vessel_position.freshness} />
                          <span className="font-mono">{formatCoord(leg.vessel_position.lat, leg.vessel_position.lon)}</span>
                          <Link href={`/vessels/${leg.vessel_id}`} className="inline-flex items-center gap-0.5 text-primary hover:underline">
                            Vessel <ExternalLink className="size-3" aria-hidden />
                          </Link>
                        </div>
                      ) : (
                        <p className="mt-2 text-xs text-muted-foreground">
                          {leg.carrier_vessel_imo
                            ? "This IMO is not among AIS-tracked vessels."
                            : "Carrier reported no IMO, so this leg cannot be matched to AIS."}
                        </p>
                      )}
                    </li>
                  ))}
                </ul>
              )}
            </CardContent>
          </Card>

          <Card>
            <CardHeader>
              <CardTitle>Arrival estimate history</CardTitle>
              <CardDescription>Every estimate is kept; newer ones never overwrite older ones.</CardDescription>
            </CardHeader>
            <CardContent>
              {estimates.length === 0 ? (
                <p className="text-sm text-muted-foreground">No estimates issued.</p>
              ) : (
                <ol className="flex flex-col gap-1 text-sm">
                  {estimates.map((e) => (
                    <li key={e.id} className="flex justify-between gap-2">
                      <span>{formatTime(e.event_at)}</span>
                      <span className="text-xs text-muted-foreground">issued {formatTime(e.event_created_at ?? e.ingested_at)}</span>
                    </li>
                  ))}
                </ol>
              )}
              {s.integration_status ? (
                <p className="mt-3 text-[11px] text-muted-foreground">
                  Integration: <Badge>{s.integration_status.replace(/_/g, " ")}</Badge>
                </p>
              ) : null}
            </CardContent>
          </Card>
        </div>
      </div>
    </div>
  );
}
