import { FlaskConical, History, Radio, WifiOff } from "lucide-react";
import type { LiveStatus } from "@/lib/live";
import { cn } from "@/lib/utils";

/**
 * States plainly what the map is showing: which kinds of data are on screen and whether
 * updates are streaming. Synthetic and historical data are always called out.
 */
export function ProvenanceBanner({
  counts,
  live,
  updatedAt,
}: {
  counts: Record<string, number>;
  live: LiveStatus;
  updatedAt: string | null;
}) {
  const synthetic = counts.synthetic ?? 0;
  const historical = counts.historical ?? 0;
  return (
    <div className="flex flex-col gap-2">
      {synthetic > 0 ? (
        <div
          role="note"
          data-testid="synthetic-banner"
          className="flex items-start gap-2 rounded-md border border-synthetic/30 bg-synthetic/10 px-3 py-2 text-sm"
        >
          <FlaskConical className="mt-0.5 size-4 shrink-0 text-synthetic" aria-hidden />
          <p>
            <span className="font-medium text-synthetic">Synthetic data.</span>{" "}
            {synthetic.toLocaleString()} vessel{synthetic === 1 ? " is" : "s are"} generated by the ChainSight AIS
            simulator. They are not real ships; configure AISStream for live AIS.
          </p>
        </div>
      ) : null}
      {historical > 0 ? (
        <div role="note" className="flex items-start gap-2 rounded-md border px-3 py-2 text-sm">
          <History className="mt-0.5 size-4 shrink-0 text-muted-foreground" aria-hidden />
          <p>{historical.toLocaleString()} vessel position(s) come from a replayed historical recording.</p>
        </div>
      ) : null}
      <div className="flex items-center gap-2 text-xs text-muted-foreground" data-testid="live-status">
        {live === "live" ? (
          <>
            <Radio className="size-3.5 text-success" aria-hidden />
            <span className="font-medium text-foreground">Streaming</span> live updates
          </>
        ) : (
          <>
            <WifiOff className={cn("size-3.5", live === "offline" ? "text-warning" : "")} aria-hidden />
            <span className="font-medium text-foreground">
              {live === "offline" ? "Live stream unavailable" : "Connecting…"}
            </span>
            <span>polling every 15 s</span>
          </>
        )}
        {updatedAt ? <span>· snapshot {new Date(updatedAt).toLocaleTimeString()}</span> : null}
      </div>
    </div>
  );
}
